#!/usr/bin/env python3
"""Writes src/OpenCLFunctions.inc: a forwarding definition for every OpenCL entry
point Leela calls (NAMES), taken from the vendored opencl/CL/cl.h. Rerun after the
OpenCL code starts using another function (the link error names it).

    python3 tools/gen_opencl_loader.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAMES = """clBuildProgram clCreateBuffer clCreateCommandQueue clCreateContext clCreateContextFromType
clCreateKernel clCreateProgramWithSource clEnqueueCopyBuffer clEnqueueNDRangeKernel clEnqueueReadBuffer
clEnqueueWriteBuffer clFinish clGetContextInfo clGetDeviceIDs clGetDeviceInfo clGetKernelWorkGroupInfo
clGetPlatformIDs clGetPlatformInfo clGetProgramBuildInfo clGetProgramInfo clReleaseCommandQueue
clReleaseContext clReleaseDevice clReleaseKernel clReleaseMemObject clReleaseProgram clRetainContext
clRetainDevice clRetainMemObject clSetKernelArg""".split()

DECL = re.compile(r"extern\s+CL_API_ENTRY\s+(.*?)\s+CL_API_CALL\s+(cl\w+)\s*\((.*?)\)\s*CL_API_SUFFIX\w*\s*;", re.S)


def split_params(text):
    parts, depth, cur = [], 0, ""
    for ch in text:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        parts.append(cur)
    return [" ".join(p.split()) for p in parts]


def param_name(p):
    m = re.search(r"\(\s*CL_CALLBACK\s*\*\s*(\w+)\s*\)", p)
    if m:
        return m.group(1)
    return re.findall(r"(\w+)\s*(?:\[\d*\])?$", p)[0]


def main():
    header = open(os.path.join(ROOT, "opencl", "CL", "cl.h"), encoding="utf-8").read()
    decls = {m.group(2): (" ".join(m.group(1).split()), m.group(3)) for m in DECL.finditer(header)}
    out = ["// Generated by tools/gen_opencl_loader.py from opencl/CL/cl.h - do not edit.", ""]
    for name in NAMES:
        ret, params = decls[name]
        ret = re.sub(r"CL_API_PREFIX\w*\s*", "", ret)
        plist = split_params(params)
        args = ", ".join(param_name(p) for p in plist)
        has_err = any(param_name(p) == "errcode_ret" for p in plist)
        out.append(f"extern \"C\" CL_API_ENTRY {ret} CL_API_CALL {name}({', '.join(plist)}) {{")
        out.append(f"    using Fn = {ret}(CL_API_CALL *)({', '.join(plist)});")
        out.append(f"    static Fn fn = reinterpret_cast<Fn>(symbol(\"{name}\"));")
        if ret == "cl_int":
            out.append("    if (!fn) return CL_LIBRARY_MISSING;")
        else:
            out.append("    if (!fn) {")
            if has_err:
                out.append("        if (errcode_ret) *errcode_ret = CL_LIBRARY_MISSING;")
            out.append("        return nullptr;")
            out.append("    }")
        out.append(f"    return fn({args});")
        out.append("}")
        out.append("")
    open(os.path.join(ROOT, "src", "OpenCLFunctions.inc"), "w", encoding="utf-8").write("\n".join(out))
    print(f"{len(NAMES)} functions")


if __name__ == "__main__":
    main()
